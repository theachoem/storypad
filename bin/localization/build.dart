// ignore_for_file: avoid_print, depend_on_referenced_packages

// This script regenerates locale-derived config from the translation JSON
// files already checked into `translations/` (the source of truth in git).
// To run, use:
// ```
// dart bin/localization/build.dart
// ```
// It performs the following tasks:
// 1. Reads `_meta.locale` / `_meta.language_name` / `_meta.native_name` from each translations/<locale>.json.
// 2. Updates the Info.plist file for iOS with the supported locales.
// 3. Updates android/app/src/main/res/xml/locales_config.xml with the supported locales.
// 4. Adds locale constants to lib/core/constants/locale_constants.dart for app to use.

import 'dart:convert';
import 'dart:io';
import 'package:xml/xml.dart';

void main() async {
  final translationFiles = Directory('translations')
      .listSync()
      .whereType<File>()
      .where((file) => file.path.endsWith('.json'))
      .toList();

  List<String> locales = [];
  Map<String, String> languageNames = {};
  Map<String, String> nativeLanguageNames = {};

  for (final file in translationFiles) {
    final Map<String, dynamic> json = jsonDecode(await file.readAsString());

    final locale = json['_meta.locale'] as String;
    locales.add(locale);
    languageNames[locale] = json['_meta.language_name'] as String;
    nativeLanguageNames[locale] = json['_meta.native_name'] as String;
  }

  locales.sort((a, b) => a == 'en' ? -1 : (b == 'en' ? 1 : a.compareTo(b)));

  await setLocalesConfigXml(locales);
  await setBundleLocalizationToInfoPlist(locales);
  await addLangageNameToAppConstant(locales, languageNames, nativeLanguageNames);
}

Future<void> setLocalesConfigXml(List<String> locales) async {
  final localesConfigFile = File('android/app/src/main/res/xml/locales_config.xml');
  final document = XmlDocument.parse(await localesConfigFile.readAsString());

  final localConfigELement = document.childElements.elementAt(0);
  while (localConfigELement.children.isNotEmpty) {
    localConfigELement.children.lastOrNull?.remove();
  }

  for (var locale in locales) {
    final localeElement = XmlElement(XmlName('locale'));
    localeElement.setAttribute("android:name", locale);
    localConfigELement.children.add(localeElement);
  }

  final newDocumentContent = document.toXmlString(pretty: true, indent: '    ').replaceAll("\"/>", "\" />");
  await localesConfigFile.writeAsString(newDocumentContent);
}

Future<void> setBundleLocalizationToInfoPlist(List<String> locales) async {
  final plistFile = File('ios/Runner/Info.plist');
  final document = XmlDocument.parse(await plistFile.readAsString());

  for (XmlNode node in document.children) {
    for (XmlNode child in node.children) {
      for (XmlNode innerChild in child.children) {
        if (innerChild.innerText == 'CFBundleLocalizations') {
          innerChild.nextElementSibling?.children.clear();
          final newChildren = locales.map((locale) => XmlElement(XmlName('string'))..innerText = locale);
          innerChild.nextElementSibling?.children.addAll(newChildren);
        }
      }
    }
  }

  final newDocumentContent = document
      .toXmlString(pretty: true, indent: '    ')
      .replaceAll("<true/>", "<true />")
      .replaceAll("<false/>", "<false />");

  await plistFile.writeAsString(newDocumentContent);
}

Future<void> addLangageNameToAppConstant(
  List<String> locales,
  Map<String, String> languageNames,
  Map<String, String> nativeLanguageNames,
) async {
  File file = File('lib/core/constants/locale_constants.dart');

  var supportedLocales = locales.map((locale) {
    final data = locale.split("-");

    return "  Locale(${[
      '"${data.first}"',
      if (data.length > 1) '"${data.last}"',
    ].join(", ")})";
  });

  final contents =
      '''
// Generated by bin/localization/build.dart
import 'dart:ui';

const kFallbackLocale = Locale("en");

const kSupportedLocales = [
${supportedLocales.join(",\n")},
];

const kLanguageNames = ${const JsonEncoder.withIndent('  ').convert(languageNames)};

const kNativeLanguageNames = ${const JsonEncoder.withIndent('  ').convert(nativeLanguageNames)};
'''
          .replaceAll("\"\n}", "\",\n}");

  file.writeAsString(contents);
}
